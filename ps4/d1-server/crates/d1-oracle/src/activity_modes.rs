//! The activity MODE table - generate `capture-rig/activity-modes.tsv` from the packages, in
//! process. This is the data behind `d1-ghost`'s destination selector (`design/d1-ghost.md` §4.1),
//! derived from the client's own content rather than hand-maintained.
//!
//! The table is the 540-entry activity index the launch seam reads (`design/activity-launch.md`
//! §2.1): each `u16` index names an activity definition, and rung 29 runs the matchmaking seeker
//! unless `activity_def[+0xA9] == 0`. That leaves exactly **21 launchable** private-match indices,
//! **393-413**, with **407 = Elimination** the stated endgame.
//!
//! ## Where the numbers come from
//!
//! `ps4_investment_globals_012f_3` block **1063** (the same block [`crate::oodle`] pins), plain,
//! carries the table at **`+0x9920`**, stride **`0x10`**, element `{u32 hash, u32 pad, i64 self-rel
//! -> definition}`. The `i64` is relative to its OWN location (`element + 0x8`); at the resolved
//! definition, `+0xA9` is the matchmaking-skip byte (`0` = launchable) and `+0x8C` is the content
//! family. All of this is content, verified against `oodle::PIN_ACTIVITY_1` (element 1's hash) and
//! `oodle::PIN_BLOCK_PLAIN_SHA256` (the whole block) so a wrong block is caught before a single row
//! is emitted.
//!
//! ⚠ The 21 launchable **display names** (Clash, Control, ... Elimination) are NOT in block 1063 -
//! they come from cross-referencing each index against the manifest, and are pinned here as a small
//! const cited to `design/activity-launch.md` §2.1. The machine columns (index, hash, launchable,
//! family) are derived from the block; the names are a pinned annotation, so the file stays honest
//! about which of its columns is data and which is a label.

use crate::error::{OracleError, Result};
use crate::oodle::{self, Content};

/// The package and block the table lives in - reused from [`crate::oodle`]'s pins, never restated.
pub const SOURCE_PACKAGE: &str = oodle::PIN_PACKAGE;
pub const SOURCE_BLOCK: u32 = oodle::PIN_BLOCK;

/// The activity table's byte offset within the plain block, its stride, and its element count.
pub const TABLE_BASE: usize = 0x9920;
pub const TABLE_STRIDE: usize = 0x10;
pub const TABLE_COUNT: usize = 540;

/// Offsets within a resolved activity definition.
pub const DEF_MATCHMAKING_SKIP: usize = 0xA9; // == 0 means "no matchmaking" == launchable
pub const DEF_CONTENT_FAMILY: usize = 0x8C;

/// The pinned launchability facts (`design/activity-launch.md` §2.1), independently re-derived here.
pub const PIN_LAUNCHABLE_COUNT: usize = 21;
pub const PIN_LAUNCHABLE_FIRST: usize = 393;
pub const PIN_LAUNCHABLE_LAST: usize = 413;
/// 407 Elimination - the stated endgame - carries `+0xA9 == 0` and `+0x8C == 0`.
pub const PIN_ELIMINATION_INDEX: usize = 407;

/// The default location of the generated table, relative to the repo root. Its OUTPUT is gitignored
/// (derived bulk output never ships); this generator is what ships.
pub const DEFAULT_PATH: &str = "capture-rig/activity-modes.tsv";

/// What this build writes into the `# GENERATED by` line.
pub const GENERATOR: &str = "d1-oracle activity-modes write";

/// The column header - the format contract between this generator and `d1-ghost`'s consumer. If it
/// changes, the consumer's parser must change with it (the consumer pins this exact string).
pub const TSV_COLUMNS: &str = "index\thash\tlaunchable\tcontent_family\tmode_name";

/// The 21 launchable display names, index-aligned from `PIN_LAUNCHABLE_FIRST`. Cited to
/// `design/activity-launch.md` §2.1; a pinned annotation, not derived from block 1063.
pub const LAUNCHABLE_NAMES: [&str; PIN_LAUNCHABLE_COUNT] = [
    "Clash",             // 393
    "Control",           // 394
    "Supremacy",         // 395
    "Mayhem Supremacy",  // 396
    "Inferno Supremacy", // 397
    "Rumble Supremacy",  // 398
    "Rumble",            // 399
    "Salvage",           // 400
    "Rift",              // 401
    "Skirmish",          // 402
    "Inferno Clash",     // 403
    "Inferno Control",   // 404
    "Mayhem Clash",      // 405
    "Zone Control",      // 406
    "Elimination",       // 407
    "Inferno Rumble",    // 408
    "Inferno Skirmish",  // 409
    "Inferno Salvage",   // 410
    "Inferno Doubles",   // 411
    "Mayhem Rumble",     // 412
    "Sparrow Racing",    // 413
];

/// One activity table row.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Mode {
    pub index: usize,
    pub hash: u32,
    /// `activity_def[+0xA9] == 0` - the client skips matchmaking, so this index is launchable.
    pub launchable: bool,
    /// `activity_def[+0x8C]` - content family.
    pub content_family: u8,
}

/// A handful of recognizable NON-launchable indices the design doc pinned (`activity-launch.md`
/// §2.1). These cannot be launched (they need matchmaking), but naming them stops the greyed
/// scroller from being a wall of "activity N". ⚠ The full 540-name set is NOT in the owned packages
/// (block 1063 carries only the activity hash + content pointers, no display string); the rest
/// would need the external Bungie `DestinyActivityDefinition` manifest, resolved locally.
pub const KNOWN_NONLAUNCHABLE_NAMES: &[(usize, &str)] = &[
    (0, "Tower"),
    (7, "Patrol: Cosmodrome"),
    (92, "Patrol: the Cosmodrome"),
    (369, "Icarus (map)"),
    (370, "Skyline (map)"),
    (371, "Last Exit (map)"),
    (372, "Floating Gardens (map)"),
];

impl Mode {
    /// The display name: the 21 launchable indices, plus the handful of pinned non-launchable ones.
    /// `None` for everything else (unnamed until the external manifest is cross-referenced).
    pub fn name(&self) -> Option<&'static str> {
        if (PIN_LAUNCHABLE_FIRST..=PIN_LAUNCHABLE_LAST).contains(&self.index) {
            return LAUNCHABLE_NAMES.get(self.index - PIN_LAUNCHABLE_FIRST).copied();
        }
        KNOWN_NONLAUNCHABLE_NAMES
            .iter()
            .find(|(i, _)| *i == self.index)
            .map(|(_, n)| *n)
    }

    /// The refusal reason a non-launchable entry renders greyed with (`design/d1-ghost.md` §4.1).
    /// Nonempty exactly when `!launchable`.
    pub fn refusal(&self) -> String {
        if self.launchable {
            String::new()
        } else {
            format!(
                "+0xA9 != 0 (matchmaking required); content family {}",
                self.content_family
            )
        }
    }
}

/// The parsed table.
#[derive(Debug, Clone)]
pub struct ModesTable {
    pub rows: Vec<Mode>,
    /// sha256 of the plain block the rows were read from - the provenance digest.
    pub block_sha256: String,
}

impl ModesTable {
    /// Read block 1063 through the Oodle decoder and parse the table.
    pub fn read(content: &mut Content) -> Result<ModesTable> {
        let plain = content
            .plain_block(SOURCE_PACKAGE, SOURCE_BLOCK)
            .map_err(|e| OracleError::Shape(format!("{SOURCE_PACKAGE} block {SOURCE_BLOCK}: {e}")))?
            .to_vec();
        ModesTable::parse(&plain)
    }

    /// Parse an already-decompressed block. Split out so the shape guards are testable without the
    /// owned-media dump.
    pub fn parse(plain: &[u8]) -> Result<ModesTable> {
        if plain.len() != oodle::PIN_BLOCK_PLAIN_LEN {
            return Err(OracleError::Shape(format!(
                "block is {} bytes, not the pinned {} - a different block, refusing to read the \
                 activity table out of it",
                plain.len(),
                oodle::PIN_BLOCK_PLAIN_LEN
            )));
        }
        // Independent shape pin: element 1's hash. A wrong base or stride would miss it.
        let elem1_hash = u32::from_le_bytes(
            plain[TABLE_BASE + TABLE_STRIDE..TABLE_BASE + TABLE_STRIDE + 4]
                .try_into()
                .unwrap(),
        );
        if elem1_hash != oodle::PIN_ACTIVITY_1 {
            return Err(OracleError::Shape(format!(
                "activity element[1] hash {elem1_hash:#010x} != pinned {:#010x} - the table base \
                 {TABLE_BASE:#x} or stride {TABLE_STRIDE:#x} is wrong",
                oodle::PIN_ACTIVITY_1
            )));
        }
        let mut rows = Vec::with_capacity(TABLE_COUNT);
        for i in 0..TABLE_COUNT {
            let off = TABLE_BASE + i * TABLE_STRIDE;
            let hash = u32::from_le_bytes(plain[off..off + 4].try_into().unwrap());
            // The i64 self-relative pointer is relative to its OWN location (off + 8).
            let rel = i64::from_le_bytes(plain[off + 8..off + 16].try_into().unwrap());
            let def = (off as i64 + 8 + rel) as usize;
            if def + DEF_MATCHMAKING_SKIP >= plain.len() {
                return Err(OracleError::Shape(format!(
                    "activity[{i}] self-rel pointer resolves to {def:#x}, outside the {}-byte block",
                    plain.len()
                )));
            }
            let launchable = plain[def + DEF_MATCHMAKING_SKIP] == 0;
            let content_family = plain[def + DEF_CONTENT_FAMILY];
            rows.push(Mode { index: i, hash, launchable, content_family });
        }
        let block_sha256 = d1_pkg::manifest::sha256_hex(plain);
        Ok(ModesTable { rows, block_sha256 })
    }

    /// The launchable indices, in order.
    pub fn launchable_indices(&self) -> Vec<usize> {
        self.rows.iter().filter(|m| m.launchable).map(|m| m.index).collect()
    }

    /// Render the TSV, byte for byte as it is shipped.
    pub fn render_tsv(&self, generator: &str) -> String {
        let mut s = String::with_capacity(self.rows.len() * 40 + 512);
        s.push_str("# \u{2b50} the 540-entry activity MODE table -> the u16 index the launch seam keys on.\n");
        s.push_str(&format!("# GENERATED by {generator} - do not hand-edit.\n"));
        s.push_str(&format!(
            "# source: {SOURCE_PACKAGE}.pkg block {SOURCE_BLOCK}, table +{TABLE_BASE:#x} stride \
             {TABLE_STRIDE:#x} count {TABLE_COUNT}\n"
        ));
        s.push_str(&format!("# sha256(plain block) = {}\n", self.block_sha256));
        s.push_str(
            "# launchable == (activity_def[+0xA9] == 0): rung 29 skips matchmaking. 21 such, \
             indices 393-413.\n",
        );
        s.push_str(
            "# mode_name is a PINNED annotation for the 21 launchable indices (activity-launch.md \
             §2.1), not a block column.\n",
        );
        s.push_str(TSV_COLUMNS);
        s.push('\n');
        for m in &self.rows {
            s.push_str(&format!(
                "{}\t{:#010x}\t{}\t{}\t{}\n",
                m.index,
                m.hash,
                if m.launchable { 1 } else { 0 },
                m.content_family,
                m.name().unwrap_or(""),
            ));
        }
        s
    }
}

/// A parsed line of the shipped TSV - the shape [`d1-ghost`]'s consumer also parses. Kept here so
/// the generator and any Rust consumer agree on the format in one place.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TsvRow {
    pub index: usize,
    pub hash: u32,
    pub launchable: bool,
    pub content_family: u8,
    pub mode_name: String,
}

/// Parse the shipped TSV back into rows, checking the column header matches [`TSV_COLUMNS`]. Any
/// consumer (including the C-GHOST-DESTS control) uses this so the format lives in one place.
pub fn parse_tsv(text: &str) -> Result<Vec<TsvRow>> {
    let mut saw_header = false;
    let mut out = Vec::new();
    for line in text.lines() {
        if line.starts_with('#') || line.trim().is_empty() {
            continue;
        }
        if !saw_header {
            if line != TSV_COLUMNS {
                return Err(OracleError::Shape(format!(
                    "TSV column header {line:?} != expected {TSV_COLUMNS:?}"
                )));
            }
            saw_header = true;
            continue;
        }
        let f: Vec<&str> = line.split('\t').collect();
        if f.len() != 5 {
            return Err(OracleError::Shape(format!("row has {} fields, want 5: {line:?}", f.len())));
        }
        let index = f[0].parse::<usize>().map_err(|e| OracleError::Shape(format!("index: {e}")))?;
        let hash = u32::from_str_radix(f[1].trim_start_matches("0x"), 16)
            .map_err(|e| OracleError::Shape(format!("hash: {e}")))?;
        let launchable = f[2] == "1";
        let content_family = f[3].parse::<u8>().map_err(|e| OracleError::Shape(format!("family: {e}")))?;
        out.push(TsvRow { index, hash, launchable, content_family, mode_name: f[4].to_string() });
    }
    if !saw_header {
        return Err(OracleError::Shape("TSV had no column header line".into()));
    }
    Ok(out)
}

/// The controls: read the real block and pin the launchability facts. **Needs the owned-media
/// dump** (like `item-index controls`). Exit 2 on failure. Reuses [`crate::profile::Control`] so
/// `report_controls` renders it exactly like every other subcommand's controls.
pub fn controls() -> Result<Vec<crate::profile::Control>> {
    let mut c = Content::open_default()?;
    let t = ModesTable::read(&mut c)?;
    let mut out = Vec::new();
    let mut push = |name: &'static str, ok: bool, detail: String| {
        out.push(crate::profile::Control { name, pass: ok, detail })
    };

    // 1. Block provenance.
    push(
        "block-sha256",
        t.block_sha256 == oodle::PIN_BLOCK_PLAIN_SHA256,
        format!("block {SOURCE_BLOCK} sha256 {}", &t.block_sha256[..16]),
    );

    // 2. Exactly 21 launchable.
    let li = t.launchable_indices();
    push(
        "launchable-count",
        li.len() == PIN_LAUNCHABLE_COUNT,
        format!("{} launchable (want {PIN_LAUNCHABLE_COUNT})", li.len()),
    );

    // 3. The launchable band is exactly 393-413, contiguous.
    let band: Vec<usize> = (PIN_LAUNCHABLE_FIRST..=PIN_LAUNCHABLE_LAST).collect();
    push(
        "launchable-band",
        li == band,
        format!("indices {:?}..{:?}", li.first(), li.last()),
    );

    // 4. 407 is Elimination, launchable, family 0.
    let e = &t.rows[PIN_ELIMINATION_INDEX];
    push(
        "elimination-407",
        e.launchable && e.content_family == 0 && e.name() == Some("Elimination"),
        format!("407 launchable={} family={} name={:?}", e.launchable, e.content_family, e.name()),
    );

    // 5. INVERTED: a known matchmaking-required index (0 = Tower) is NOT launchable. If this
    //    "passes" as launchable the read is meaningless.
    push(
        "tower-0-is-not-launchable",
        !t.rows[0].launchable,
        format!("index 0 launchable={} (must be false)", t.rows[0].launchable),
    );

    // 6. The TSV round-trips through the shared parser.
    let text = t.render_tsv(GENERATOR);
    let reparsed = parse_tsv(&text)?;
    let round_trips = reparsed.len() == TABLE_COUNT
        && reparsed[PIN_ELIMINATION_INDEX].mode_name == "Elimination"
        && reparsed[PIN_ELIMINATION_INDEX].launchable;
    push(
        "tsv-round-trip",
        round_trips,
        format!("{} rows re-parse; 407 = Elimination", reparsed.len()),
    );

    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A refusal reason is nonempty exactly for non-launchable rows.
    #[test]
    fn refusal_reason_tracks_launchability() {
        let yes = Mode { index: 407, hash: 1, launchable: true, content_family: 0 };
        let no = Mode { index: 0, hash: 2, launchable: false, content_family: 4 };
        assert!(yes.refusal().is_empty());
        assert!(!no.refusal().is_empty());
        assert!(no.refusal().contains("matchmaking"));
    }

    /// The name annotation covers exactly the launchable band.
    #[test]
    fn names_cover_the_band() {
        assert_eq!(Mode { index: 407, hash: 0, launchable: true, content_family: 0 }.name(), Some("Elimination"));
        assert_eq!(Mode { index: 393, hash: 0, launchable: true, content_family: 0 }.name(), Some("Clash"));
        assert_eq!(Mode { index: 392, hash: 0, launchable: false, content_family: 0 }.name(), None);
        assert_eq!(Mode { index: 414, hash: 0, launchable: false, content_family: 0 }.name(), None);
    }

    /// The TSV parser rejects a wrong header rather than silently reading shifted columns.
    #[test]
    fn parser_rejects_a_wrong_header() {
        let bad = "# c\nindex\thash\n1\t0x2\n";
        assert!(parse_tsv(bad).is_err());
    }
}
