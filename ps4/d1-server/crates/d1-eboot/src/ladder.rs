//! **The world-controller state machine, read out of the client's own RTTI** - the Rust port of
//! `capture-rig/state-machine.py`, behaviour-for-behaviour, in-process instead of 36 subprocesses.
//!
//! Destiny's boot/activity ladder is not a switch statement. It is **one C++ class per rung**, all
//! deriving from `c_world_controller_tiger_base_state_handler`, each with a 10-slot vtable:
//!
//! ```text
//!   +0x20  slot 4  ENTER   - called on the NEW rung's handler, with (old_state, reason)
//!   +0x28  slot 5  EXIT    - called on the OLD rung's handler, with (new_state, reason)
//!   +0x30  slot 6  the UPDATE GUARD - a predicate; UPDATE runs only when it returns non-zero
//!   +0x38  slot 7  UPDATE  - the per-frame tick. This is where the rung decides to advance.
//!   +0x10  slot 2  a shared base no-op (0x752d30) - NOT part of the transition pair
//!   +0x40  slot 8  0x1092140 in the base - NOT part of the transition pair
//! ```
//!
//! ⛔ **RETRACTION 2026-08-10 (carried from the prototype).** An earlier reading labelled `+0x10`
//! ENTER and `+0x40` EXIT. That is exactly backwards: the per-transition pair is **slots 4/5
//! (`+0x20`/`+0x28`)**, proved by the client's own transition pump `FUN_00782300`, where each
//! dispatch sits immediately after the printf that narrates it ("Leaving state '%s' ..." then
//! `call [rax+0x28]`; "Entering state '%s' ..." then `call [rax+0x20]`). The controls in this
//! module re-derive that pairing on every run and FAIL if the labels are ever swapped back.
//!
//! The transition primitives (`design/` census, verified by the rung-28 control):
//!
//! ```text
//!   0x782720(new_state, reason, arg3)   the real one
//!   0x783690(new_state, reason)         -> 0x782720(new_state, reason, 0)
//!   0x782710(new_state)                 -> 0x782720(new_state, 0, 0)
//! ```
//!
//! **The state id is literally the rung number** - `mov edi, 0x1d ; call 0x783690` is
//! `request(setup:matchmaking)`.
//!
//! ## What is ported, and what deliberately is not
//!
//! * The prototype read handler classes out of `capture-rig/eboot-types.tsv` (itself generated by
//!   `d1-eboot rtti --tsv`). This module asks [`crate::rtti::harvest`] directly - the same fact
//!   without a file that can go stale. The byte-for-byte golden diff against the prototype is what
//!   licenses the substitution (`tests/ladder.rs`).
//! * Vtable slots are `R_X86_64_RELATIVE` relocations, **zero in the file**; they are read through
//!   [`crate::reloc::by_slot`], never as literal bytes. A slot with no relocation reads `0`,
//!   exactly as the prototype's `reloc --slot` parse did.
//! * Function-name and diagnostic-string annotations still come from the generated TSVs
//!   (`capture-rig/eboot-atlas.tsv`, `capture-rig/diagnostic-catalogue.tsv`), with the prototype's
//!   refusals intact: `#` provenance lines are skipped, and the controls assert the loaders
//!   actually loaded (the S3 lesson: a wrong column name once returned `{}` silently and every
//!   annotation went blank while looking like an empty atlas).
//! * **One deviation, on purpose:** where the prototype's `eboot()` wrapper swallowed a subprocess
//!   exit 1 and rendered a frame-pointer-omitted handler function as a silently empty body
//!   (`--rung 1`, `--rung 28 :: slot40`, ...), this port decodes it - the address came out of a
//!   vtable slot, which is a confirmed function start (`disasm::anchor_for_known_start`'s
//!   rationale) - and refuses loudly for a user-supplied `--fn` address that is neither a prologue
//!   nor a known function start. A silent empty is this project's most-repeated false negative.
//! * A second added refusal: [`require_sane`] rejects an image that yields zero handlers or zero
//!   UPDATE overrides, because the prototype would render that as a plausible all-`-` table.
//!
//! Exit 2 if a control fails. Nothing here may be cited on a failing control.

