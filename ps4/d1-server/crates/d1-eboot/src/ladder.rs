/// Names, extents and diagnostic strings from the generated TSVs. Missing files load as empty
/// maps (the prototype's behaviour - the render degrades, the controls refuse); an unreadable
/// existing file is an error.
#[derive(Debug, Default)]
pub struct Annotations {
    /// vaddr -> atlas name. Empty names are stored (and render as empty), matching the prototype.
    pub atlas: HashMap<u64, String>,
    /// vaddr -> the atlas's derived `end` column, so nothing here hard-codes a body size.
    pub atlas_ends: HashMap<u64, u64>,
    /// function vaddr -> [(string vaddr, text)] from the diagnostic catalogue, in file order.
    pub strings_by_fn: HashMap<u64, Vec<(u64, String)>>,
}

/// `int(s, 16)` with an optional `0x` prefix, as the prototype's loaders accepted.
fn parse_hex(s: &str) -> Option<u64> {
    let t = s.trim();
    let t = t.strip_prefix("0x").or_else(|| t.strip_prefix("0X")).unwrap_or(t);
    if t.is_empty() {
        return None;
    }
    u64::from_str_radix(t, 16).ok()
}

/// Undo csv-module quoting on one tab-separated field. Verified equivalent to Python's
/// `csv.DictReader(delimiter="\t")` over both shipped TSVs (no embedded tabs or newlines exist;
/// 22 atlas rows carry quoted fields with doubled inner quotes).
fn unquote(f: &str) -> String {
    if f.len() >= 2 && f.starts_with('"') && f.ends_with('"') {
        f[1..f.len() - 1].replace("\"\"", "\"")
    } else {
        f.to_string()
    }
}

/// Read the named columns of one of the rig's TSVs.
///
/// ⚠ Skips `#` comment lines: `diagnostic-catalogue.tsv` carries a provenance line as line 1 (its
/// freshness guard). A reader that took that comment as the header row would hand back nothing but
/// empties - the same silent shape as the S3 bug the controls pin.
fn read_tsv(path: &Path, want: &[&str]) -> std::io::Result<Option<Vec<Vec<String>>>> {
    let text = match std::fs::read_to_string(path) {
        Ok(t) => t,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(e) => return Err(e),
    };
    let mut lines = text.lines().filter(|l| !l.starts_with('#'));
    let Some(header) = lines.next() else { return Ok(Some(Vec::new())) };
    let cols: Vec<&str> = header.split('\t').collect();
    let ix: Vec<Option<usize>> = want.iter().map(|w| cols.iter().position(|c| c == w)).collect();
    let mut out = Vec::new();
    for ln in lines {
        let fields: Vec<&str> = ln.split('\t').collect();
        out.push(
            ix.iter()
                .map(|i| i.and_then(|i| fields.get(i)).map(|f| unquote(f)).unwrap_or_default())
                .collect(),
        );
    }
    Ok(Some(out))
}

pub fn load_annotations(atlas_tsv: &Path, diag_tsv: &Path) -> std::io::Result<Annotations> {
    let mut ann = Annotations::default();
    if let Some(rows) = read_tsv(atlas_tsv, &["vaddr", "end", "name"])? {
        for r in rows {
            let Some(va) = parse_hex(&r[0]) else { continue };
            // Names: last row wins (the prototype's dict insert). Ends: first row wins (the
            // prototype's atlas_end returned on first match). Duplicates do not occur in practice.
            ann.atlas.insert(va, r[2].clone());
            if let Some(end) = parse_hex(&r[1]) {
                ann.atlas_ends.entry(va).or_insert(end);
            }
        }
    }
    if let Some(rows) = read_tsv(diag_tsv, &["fn", "vaddr", "text"])? {
        for r in rows {
            let (Some(f), Some(va)) = (parse_hex(&r[0]), parse_hex(&r[1])) else { continue };
            ann.strings_by_fn.entry(f).or_default().push((va, r[2].clone()));
        }
    }
    Ok(ann)
}

// ── the annotated function reader ────────────────────────────────────────────────────────────

/// `mov edi, <imm>` detector - the prototype's `EDI_RE` (`0x` lowercase hex, or bare decimal,
/// nothing after).
fn edi_imm(op_str: &str) -> Option<u64> {
    let rest = op_str.strip_prefix("edi,")?.trim();
    if let Some(h) = rest.strip_prefix("0x") {
        if !h.is_empty() && h.bytes().all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b)) {
            return u64::from_str_radix(h, 16).ok();
        }
        None
    } else if !rest.is_empty() && rest.bytes().all(|b| b.is_ascii_digit()) {
        rest.parse().ok()
    } else {
        None
    }
}

/// `call qword ptr [rax+0xNN]` displacement - the prototype's vcall regex.
fn rax_disp(op_str: &str) -> Option<u64> {
    let rest = op_str.strip_prefix("qword ptr [rax+0x")?;
    let end = rest.find(']')?;
    let h = &rest[..end];
    if !h.is_empty() && h.bytes().all(|b| b.is_ascii_hexdigit()) {
        u64::from_str_radix(h, 16).ok()
    } else {
        None
    }
}

/// The subprocess `disasm --count N` behaviour the prototype consumed: decode a generous range,
/// truncate to N instructions, and (as `--count` did) drop the truncation marker.
fn disasm_count(image: &Image, addr: u64, limit: usize, anchor: Anchor) -> Result<Vec<Insn>> {
    let end = addr + limit as u64 * 15 + 16;
    let mut d = disasm::disasm_range(image, addr, end, anchor)?;
    d.insns.truncate(limit);
    Ok(d.insns)
}

/// One rendered line, exactly as `d1-eboot disasm`'s text printer produces it (the prototype
/// annotated that subprocess output line by line).
fn base_line(i: &Insn) -> String {
    let annot = match (i.branch_target, i.rip_target) {
        (Some(t), _) => format!("   ; -> {t:#x}"),
        (_, Some(t)) => format!("   ; [{t:#x}]"),
        _ => String::new(),
    };
    format!("0x{:08x}  {:<30} {:<8} {}{}", i.address, i.bytes, i.mnemonic, i.op_str, annot)
}

fn truncate_chars(s: &str, n: usize) -> String {
    s.chars().take(n).collect()
}

/// Disassemble one function, annotating call targets and decoding state transitions - the
/// prototype's `read_function`, returned as a string (with its leading blank line).
///
/// `known_start`: the address came out of a vtable slot, i.e. it is a confirmed function start,
/// so a frame-pointer-omitted body is decoded (`Anchor::Forced`) rather than silently skipped as
/// the prototype did. A user-supplied address that is neither a prologue nor a known function
/// start is refused loudly - never decoded from a guess (ATLAS §4.5).
pub fn read_function(
    image: &Image,
    addr: u64,
    ann: &Annotations,
    limit: usize,
    known_start: bool,
) -> Result<String> {
    let anchor = if disasm::is_prologue(image, addr) {
        Anchor::Prologue
    } else if known_start || image.containing_function(addr).start == Some(addr) {
        Anchor::Forced
    } else {
        return Err(ImageError::NotAPrologue { vaddr: addr });
    };
    let insns = disasm_count(image, addr, limit, anchor)?;

    let mut out = String::new();
    let bar = "=".repeat(96);
    let name = ann.atlas.get(&addr).map(String::as_str).unwrap_or("(unnamed)");
    let _ = writeln!(out, "\n{bar}\n {addr:#x}  {name}\n{bar}");

    let mut pending_edi: Option<(u64, u64)> = None;
    let mut transitions: Vec<(u64, Option<u64>, String)> = Vec::new();
    for i in &insns {
        let mut line = base_line(i);
        if i.mnemonic == "mov" {
            if let Some(v) = edi_imm(&i.op_str) {
                pending_edi = Some((i.address, v));
            }
        }
        if (i.mnemonic == "call" || i.mnemonic == "jmp") && i.branch_target.is_some() {
            let target = i.branch_target.unwrap();
            let name = ann.atlas.get(&target).map(String::as_str).unwrap_or("");
            if TRANSITION_FNS.contains(&target) {
                if let Some((_, rung)) = pending_edi {
                    let state = if (rung as usize) < STATES.len() {
                        STATES[rung as usize]
                    } else {
                        "?"
                    };
                    let _ = write!(line, "   ⭐ REQUEST STATE {rung} = {state}");
                    transitions.push((i.address, Some(rung), state.to_string()));
                } else {
                    let _ = write!(line, "   ⭐ REQUEST STATE <register - data-driven>");
                    transitions.push((i.address, None, "<register>".to_string()));
                }
            } else if !name.is_empty() {
                let _ = write!(line, "   ; {}", truncate_chars(name, 60));
            }
            if !TRANSITION_FNS.contains(&target) {
                pending_edi = None;
            }
        }
        let _ = writeln!(out, "{line}");
    }

    if let Some(refs) = ann.strings_by_fn.get(&addr) {
        if !refs.is_empty() {
            let _ = writeln!(out, "\n  ── diagnostic strings referenced by {addr:#x} ──");
            for (vaddr, txt) in refs {
                let _ = writeln!(out, "    {vaddr:#x}  {}", truncate_chars(txt, 110));
            }
        }
    }
    if !transitions.is_empty() {
        let _ = writeln!(out, "\n  ── state transitions requested ──");
        for (site, rung, state) in &transitions {
            let label = match rung {
                Some(r) => format!("{r} = {state}"),
                None => state.clone(),
            };
            let _ = writeln!(out, "    {site:#x}  ->  {label}");
        }
    }
    Ok(out)
}

