/// The six slot pointers, in the prototype's JSON key order. `0` = no relocation for the slot
/// (or `__cxa_pure_virtual`), exactly as the prototype's `reloc --slot` parse yielded.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub struct Slots {
    pub slot10: u64,
    pub enter: u64,
    pub exit: u64,
    pub update_guard: u64,
    pub update: u64,
    pub slot40: u64,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub struct Overridden {
    pub slot10: bool,
    pub enter: bool,
    pub exit: bool,
    pub update_guard: bool,
    pub update: bool,
    pub slot40: bool,
}

impl Slots {
    pub fn by_name(&self, name: &str) -> u64 {
        match name {
            "slot10" => self.slot10,
            "enter" => self.enter,
            "exit" => self.exit,
            "update_guard" => self.update_guard,
            "update" => self.update,
            "slot40" => self.slot40,
            _ => 0,
        }
    }
}

impl Overridden {
    pub fn by_name(&self, name: &str) -> bool {
        match name {
            "slot10" => self.slot10,
            "enter" => self.enter,
            "exit" => self.exit,
            "update_guard" => self.update_guard,
            "update" => self.update,
            "slot40" => self.slot40,
            _ => false,
        }
    }
}

/// One rung's handler. Field order is the prototype's JSON key order - `d1-trace` parses this
/// shape (`class`/`short`/`rung`/`state` declared, extras ignored), so it must not be reordered.
#[derive(Debug, Clone, Serialize)]
pub struct Handler {
    pub class: String,
    pub short: String,
    pub rung: Option<u32>,
    pub state: Option<String>,
    pub vtable: u64,
    pub slots: Slots,
    pub overridden: Overridden,
}

fn slot_at(by_slot: &HashMap<u64, u64>, vtable: u64, off: u64) -> u64 {
    by_slot.get(&(vtable + off)).copied().unwrap_or(0)
}

fn slots_of(by_slot: &HashMap<u64, u64>, vtable: u64) -> Slots {
    Slots {
        slot10: slot_at(by_slot, vtable, 0x10),
        enter: slot_at(by_slot, vtable, 0x20),
        exit: slot_at(by_slot, vtable, 0x28),
        update_guard: slot_at(by_slot, vtable, 0x30),
        update: slot_at(by_slot, vtable, 0x38),
        slot40: slot_at(by_slot, vtable, 0x40),
    }
}

/// Enumerate the `c_world_controller_state_*_handler` classes from RTTI and read each vtable's
/// slots through the relocation table. Sorted by rung (rung-less classes, should any appear, sort
/// last - and fail the controls).
pub fn load_handlers(image: &Image) -> Result<Vec<Handler>> {
    const PREFIX: &str = "c_world_controller_state_";
    const SUFFIX: &str = "_handler";
    let by_slot = reloc::by_slot(image)?;
    let r = rtti::harvest(image)?;
    let base = slots_of(&by_slot, BASE_VTABLE);
    let mut handlers = Vec::new();
    for t in &r.types {
        if !(t.name.starts_with(PREFIX) && t.name.ends_with(SUFFIX)) {
            continue;
        }
        let Some(&vtable) = t.vtables.first() else { continue };
        let short = &t.name[PREFIX.len()..t.name.len() - SUFFIX.len()];
        let rung = CLASS_TO_RUNG.iter().find(|(s, _)| *s == short).map(|&(_, r)| r);
        let slots = slots_of(&by_slot, vtable);
        handlers.push(Handler {
            class: t.name.clone(),
            short: short.to_string(),
            rung,
            state: rung.map(|r| STATES[r as usize].to_string()),
            vtable,
            slots,
            overridden: Overridden {
                slot10: slots.slot10 != base.slot10,
                enter: slots.enter != base.enter,
                exit: slots.exit != base.exit,
                update_guard: slots.update_guard != base.update_guard,
                update: slots.update != base.update,
                slot40: slots.slot40 != base.slot40,
            },
        });
    }
    handlers.sort_by_key(|h| (h.rung.is_none(), h.rung.unwrap_or(0)));
    Ok(handlers)
}

/// Refuse a table that would be a plausible lie. The prototype rendered an image with no
/// relocations (all slots 0, everything "inherits the base") or no RTTI (an empty table) without
/// complaint; both are the all-too-plausible face of a broken input. Controls catch it too, but
/// the default render path must not need them to.
pub fn require_sane(handlers: &[Handler]) -> std::result::Result<(), String> {
    if handlers.is_empty() {
        return Err(
            "no c_world_controller_state_*_handler classes in this image's RTTI - this is not \
             the pinned client build, or its RTTI/relocations are absent. Refusing to print an \
             empty ladder as if it were a finding."
                .into(),
        );
    }
    if handlers.iter().all(|h| !h.overridden.update) {
        return Err(
            "no handler overrides UPDATE - the relocation table yielded no vtable slots, so \
             every column would read '-' (inherits the base) and the table would be a plausible \
             lie. Base UPDATE is pure-virtual; on a real image every rung overrides it."
                .into(),
        );
    }
    Ok(())
}

