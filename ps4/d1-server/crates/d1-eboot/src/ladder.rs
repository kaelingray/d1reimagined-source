/// The full-ladder table, byte-for-byte the prototype's default output.
pub fn render_table(handlers: &[Handler]) -> String {
    let mut out = String::new();
    let mut header = format!("{:>4}  {:<38} ", "rung", "state");
    header.push_str(
        &TABLE_ORDER.iter().map(|s| format!("{s:>10}")).collect::<Vec<_>>().join(" "),
    );
    let _ = writeln!(out, "{header}");
    for h in handlers {
        let rung = match h.rung {
            Some(r) => format!("{r:>4}"),
            // The prototype crashed on a rung-less handler; "?" keeps the row visible and the
            // controls loud. Unreachable on the pinned image (all 35 classes map).
            None => format!("{:>4}", "?"),
        };
        let state = h.state.as_deref().unwrap_or(&h.short);
        let cells = TABLE_ORDER
            .iter()
            .map(|s| {
                let cell = if h.overridden.by_name(s) {
                    format!("{:#010x}", h.slots.by_name(s))
                } else {
                    "-".to_string()
                };
                format!("{cell:>10}")
            })
            .collect::<Vec<_>>()
            .join(" ");
        let _ = writeln!(out, "{rung}  {state:<38} {cells}");
    }
    let _ = writeln!(
        out,
        "\n{} handlers. '-' = inherits the base (c_world_controller_tiger_base_state_handler, \
         vtable {:#x}).",
        handlers.len(),
        BASE_VTABLE
    );
    let _ = writeln!(
        out,
        "ENTER (+0x20, slot 4) and EXIT (+0x28, slot 5) are the per-transition pair - dispatched \
         by\nthe pump 0x782300 immediately after its own \"Entering/Leaving state\" printfs."
    );
    let _ = writeln!(
        out,
        "UPDATE (+0x38) is the per-frame tick - the rung's own decision to advance lives there,\n\
         gated by the predicate at +0x30."
    );
    out
}

/// The handlers as JSON, byte-for-byte the prototype's `json.dumps(handlers, indent=1)` (no
/// trailing newline - the caller prints one, as `print()` did).
pub fn to_json_py(handlers: &[Handler]) -> String {
    let mut buf = Vec::new();
    let fmt = serde_json::ser::PrettyFormatter::with_indent(b" ");
    let mut ser = serde_json::Serializer::with_formatter(&mut buf, fmt);
    handlers.serialize(&mut ser).expect("in-memory serialization cannot fail");
    String::from_utf8(buf).expect("serde_json emits utf-8")
}

// ── controls ─────────────────────────────────────────────────────────────────────────────────

#[derive(Debug, Clone, Serialize)]
pub struct ControlRow {
    pub label: String,
    pub passed: bool,
    pub detail: String,
}

/// Every control the prototype ran, with its exact labels, details and rendering. Returns the
/// rendered text (byte-for-byte the prototype's `--controls` output), the overall verdict, and
/// the rows for embedding in `d1-eboot controls`.
pub fn controls(image: &Image, ann: &Annotations) -> Result<(String, bool, Vec<ControlRow>)> {
    let mut checks: Vec<ControlRow> = Vec::new();
    let mut push = |passed: bool, label: &str, detail: String| {
        checks.push(ControlRow { label: label.to_string(), passed, detail });
    };

    let by_slot = reloc::by_slot(image)?;

    // The vtable slot reader, against THE-CHAIN §3.2's hand-read s_investment_utility_context.
    let inv = 0x18F_5AF0u64;
    let (a, b) = (slot_at(&by_slot, inv, 0x80), slot_at(&by_slot, inv, 0xC8));
    push(
        a == 0x26_0A10 && b == 0x26_0BD0,
        "vtable slot reader reproduces the pinned s_investment_utility_context slots",
        format!("[+0x80]={a:#x} [+0xc8]={b:#x}"),
    );

    let handlers = load_handlers(image)?;
    push(
        handlers.len() == 35,
        "RTTI yields 35 world-controller state handlers",
        format!("[{}]", handlers.len()),
    );
    let named: Vec<&Handler> = handlers.iter().filter(|h| h.rung.is_some()).collect();
    push(
        named.len() == 35,
        "every handler class maps to a rung in the state table",
        format!("[{}/35]", named.len()),
    );

    let update_of =
        |r: u32| handlers.iter().find(|h| h.rung == Some(r)).map(|h| h.slots.update).unwrap_or(0);
    // The census (THE-CHAIN §5) independently found rung 29 requested inside 0x7A6D60. That
    // function must be rung 28's UPDATE if the vtable model is right - two derivations, one answer.
    push(
        update_of(28) == 0x7A_6D60,
        "rung 28 UPDATE == 0x7A6D60, the census's requesting site for rung 29",
        format!("{:#x}", update_of(28)),
    );
    push(
        update_of(25) == 0x7A_3750,
        "rung 25 UPDATE == 0x7A3750, which the atlas names cleanup_handler::vfunc[7]",
        format!("{:#x}", update_of(25)),
    );
    push(
        update_of(30) == 0x7A_5250,
        "rung 30 UPDATE == 0x7A5250, the census's requesting site for rung 31",
        format!("{:#x}", update_of(30)),
    );
    push(
        update_of(27) == 0x7A_AF60,
        "rung 27 (orbit) UPDATE == 0x7AAF60",
        format!("{:#x}", update_of(27)),
    );

    // The base leaves UPDATE pure-virtual (slot is 0) and shares +0x30 with every derived class.
    // So "every rung overrides its update" is a property of the ABI, not of our reading.
    let base = slots_of(&by_slot, BASE_VTABLE);
    push(
        base.update_guard == 0x79_14E0,
        "base +0x30 is the shared 0x7914E0 thunk (inherited, so a real negative exists)",
        format!("{:#x}", base.update_guard),
    );
    push(
        base.update == 0,
        "base UPDATE (+0x38) is pure-virtual - every rung must supply its own",
        format!("{:#x}", base.update),
    );
    let all_override = named.iter().filter(|h| h.overridden.update).count();
    push(all_override == 35, "all 35 handlers override UPDATE", format!("[{all_override}/35]"));

    // The state-id decode: rung 29's request site must read as an immediate 0x1d.
    let r28 = disasm_count(image, 0x7A_6D60, 4000, Anchor::Prologue).unwrap_or_default();
    push(
        r28.iter().any(|i| i.op_str.contains("edi, 0x1d"))
            && r28.iter().any(|i| i.branch_target == Some(0x78_3690)),
        "rung 28's update contains `mov edi, 0x1d` -> call 0x783690 (id == rung number)",
        String::new(),
    );

    // ── ENTER/EXIT are slots 4/5 - derived, not transcribed. Walk the transition pump and, for
    // each emit of a *catalogued* diagnostic string, take the next indirect `call [rax+N]`. The
    // pump narrates itself, so the printf immediately preceding each dispatch names it. This
    // control FAILS if the labels are swapped back - the only kind of control worth having here.
    // ⚠ Key by VADDR across the whole catalogue, not by the pump's own bucket: the catalogue
    // attributes each string to its FIRST referencing function, and "Leaving state" is also lea'd
    // by the teardown path 0x782010, which sorts earlier. (The prototype's control caught exactly
    // that, first run.)
    let pump_strings: HashMap<u64, &str> = ann
        .strings_by_fn
        .values()
        .flatten()
        .map(|(va, txt)| (*va, txt.as_str()))
        .collect();
    // ⚠ Bound the walk to the pump's own body, from the atlas's derived `end` column - `--count`
    // overruns into the next functions, which dispatch on their own vtables.
    let pump_end = ann.atlas_ends.get(&TRANSITION_PUMP).copied();
    let pump = disasm_count(image, TRANSITION_PUMP, 4000, Anchor::Prologue).unwrap_or_default();
    let mut narrated: Vec<(&str, u64)> = Vec::new();
    let mut pending_text: Option<&str> = None;
    for i in &pump {
        if let Some(end) = pump_end {
            if i.address >= end {
                break;
            }
        }
        if i.branch_target.is_none() {
            if let Some(rt) = i.rip_target {
                if let Some(&txt) = pump_strings.get(&rt) {
                    pending_text = Some(txt);
                }
            }
        }
        if i.mnemonic == "call" {
            if let Some(disp) = rax_disp(&i.op_str) {
                if let Some(txt) = pending_text.take() {
                    narrated.push((txt, disp));
                }
            }
        }
    }
    let dispatched_after = |needle: &str| -> BTreeSet<u64> {
        narrated.iter().filter(|(t, _)| t.contains(needle)).map(|&(_, d)| d).collect()
    };
    let render_set = |s: &BTreeSet<u64>| -> String {
        if s.is_empty() {
            "NO DISPATCH FOUND".to_string()
        } else {
            s.iter().map(|d| format!("{d:#x}")).collect::<Vec<_>>().join(" ")
        }
    };
    let after = dispatched_after("Leaving state");
    push(
        after == BTreeSet::from([EXIT_SLOT]),
        &format!(
            "EXIT is slot {} (+{:#x}) - the dispatch that follows the pump's own \"Leaving \
             state\" emit",
            EXIT_SLOT / 8,
            EXIT_SLOT
        ),
        render_set(&after),
    );
    let after = dispatched_after("Entering state");
    push(
        after == BTreeSet::from([ENTER_SLOT]),
        &format!(
            "ENTER is slot {} (+{:#x}) - the dispatch that follows the pump's own \"Entering \
             state\" emit",
            ENTER_SLOT / 8,
            ENTER_SLOT
        ),
        render_set(&after),
    );
    // The corroboration, from the ABI: ENTER is pure-virtual in the base (every rung must have
    // one) while EXIT inherits a shared no-op. The retracted labelling put ENTER on +0x10, which
    // the base implements - i.e. it claimed a mandatory hook was optional.
    push(
        base.enter == 0 && base.exit == 0x75_2D30,
        "base ENTER is pure-virtual and base EXIT is the shared no-op (ABI corroboration)",
        format!("enter={:#x} exit={:#x}", base.enter, base.exit),
    );

    // ── THE TWO LOADERS ACTUALLY LOAD (the S3 lesson). An empty container is never
    // self-evidently wrong; assert it is not empty, so a wrong column name fails a control
    // instead of blanking every annotation silently.
    push(
        ann.atlas.len() > 40_000,
        "load_atlas() returns names for the whole atlas (S3: a wrong column name returned {} and \
         was swallowed)",
        format!("[{} rows]", ann.atlas.len()),
    );
    let pump_name = ann.atlas.get(&TRANSITION_PUMP).map(String::as_str).unwrap_or("MISSING");
    push(
        !pump_name.is_empty() && pump_name != "MISSING",
        &format!(
            "...and the pump {TRANSITION_PUMP:#x} resolves to a name, not an empty cell"
        ),
        pump_name.to_string(),
    );
    push(
        ann.strings_by_fn.len() > 500 && pump_strings.len() > 1000 && narrated.len() == 2,
        "load_strings_by_fn() reads the diagnostic catalogue past its provenance line, and the \
         pump body narrates exactly two dispatches (ENTER and EXIT)",
        match pump_end {
            Some(end) => format!(
                "[{} fns, {} strings, {} narrated dispatches in {TRANSITION_PUMP:#x}..{end:#x}]",
                ann.strings_by_fn.len(),
                pump_strings.len(),
                narrated.len()
            ),
            None => "[atlas end MISSING]".to_string(),
        },
    );

    let failed = checks.iter().filter(|c| !c.passed).count();
    let mut text = String::new();
    for c in &checks {
        let mut line = format!("{}  {}", if c.passed { "PASS" } else { "FAIL" }, c.label);
        if !c.detail.is_empty() {
            let _ = write!(line, "  [{}]", c.detail);
        }
        let _ = writeln!(text, "{line}");
    }
    let _ = writeln!(
        text,
        "\n{}",
        if failed == 0 {
            "ALL CONTROLS PASS".to_string()
        } else {
            format!("{failed} CONTROL(S) FAILED")
        }
    );
    Ok((text, failed == 0, checks))
}

#[cfg(test)]
