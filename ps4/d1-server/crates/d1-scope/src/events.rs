// Attribution - which surface did this address belong to?
// ─────────────────────────────────────────────────────────────────────────────────────────────────

/// The **declared** byte extent of a registry field type, unclamped.
///
/// ⚠ Deliberately different from [`crate::sampler::parse_field_ty`], which clamps array lengths so
/// a table cell stays readable. Attribution must use the real extent: a store at byte 300 of a
/// 512-byte array belongs to that surface, and a display clamp would silently orphan it.
/// Returns `None` for types with no unambiguous machine extent (`struct[]`, `u8[40*0xD8]`).
pub fn declared_extent(ty: &str) -> Option<u64> {
    let t = ty.trim();
    if t == "[U]" {
        return None;
    }
    if let Some(rest) = t.strip_prefix("char[") {
        return parse_len(rest.trim_end_matches(']')).map(|n| n as u64);
    }
    if let Some(base) = Ty::parse(t) {
        return Some(base.size() as u64);
    }
    if let Some((base, rest)) = t.split_once('[') {
        let inner = rest.trim_end_matches(']');
        let n = parse_len(inner)? as u64;
        if let Some(bt) = Ty::parse(base) {
            return Some(bt.size() as u64 * n);
        }
        if base == "ptr" {
            return Some(8 * n);
        }
    }
    None
}

/// How far past its base a surface is known to extend. `None` fields ⇒ the base word only.
pub fn surface_span(s: &SurfaceView) -> u64 {
    s.fields
        .iter()
        .filter_map(|f| declared_extent(&f.ty).map(|w| f.off + w))
        .max()
        .unwrap_or(8)
}

#[derive(Clone, Debug, Serialize)]
pub struct Attribution {
    /// The surface the ADDRESS lands in, derived independently of what the slot claimed.
    pub surface: Option<String>,
    pub field: Option<String>,
    /// `by-address` · `by-address+field` · `unattributed`.
    pub how: &'static str,
    /// ⭐ The slot said one thing and the address said another. Two derivations disagreeing is a
    /// finding, not noise - it means either the registry offset is wrong or the arm went somewhere
    /// other than where it was asked to.
    pub disagreement: Option<String>,
}

/// ⭐ Attach by ADDRESS, then compare against what the slot claimed.
///
/// The slot already knows which surface it was armed for, so attribution by slot would always
/// "succeed" - and would therefore never catch a registry offset that is wrong. Deriving the
/// surface a second way, from the address alone, is what makes the answer falsifiable.
pub fn attach_by_address(
    surfaces: &[SurfaceView],
    addr: u64,
    len: u64,
    slot_surface: Option<&str>,
) -> Attribution {
    let mut hit: Option<(&SurfaceView, u64)> = None;
    for s in surfaces {
        let Resolved::Addr(base) = s.resolved else { continue };
        let span = surface_span(s);
        // Overlap, not containment: an 8-byte watch straddling the end of a surface still touched
        // it, and reporting that as "unattributed" would hide the interesting case.
        if addr < base + span && base < addr + len.max(1) {
            let off = addr.saturating_sub(base);
            match hit {
                // The tightest enclosing surface wins - nested/overlapping registry entries exist
                // (a pool header and the pool it heads), and the more specific one is the answer.
                Some((prev, _)) if surface_span(prev) <= span => {}
                _ => hit = Some((s, off)),
            }
        }
    }

    let (surface, field, how) = match hit {
        None => (None, None, "unattributed"),
        Some((s, off)) => {
            let f = s.fields.iter().find(|f| {
                let w = declared_extent(&f.ty).unwrap_or(8);
                off >= f.off && off < f.off + w
            });
            (
                Some(s.name.clone()),
                f.map(|f| f.name.clone()),
                if f.is_some() { "by-address+field" } else { "by-address" },
            )
        }
    };

    let disagreement = match (slot_surface, surface.as_deref()) {
        (Some(claimed), Some(found)) if claimed != found => Some(format!(
            "the slot was armed for {claimed:?} but {addr:#x} lands in {found:?} - one of the two \
             is wrong, and a registry offset is the likelier of them"
        )),
        (Some(claimed), None) => Some(format!(
            "the slot was armed for {claimed:?} but {addr:#x} lands in NO resolved surface this \
             tick - the chain moved, or the surface did not resolve"
        )),
        _ => None,
    };

    Attribution { surface, field, how, disagreement }
}

/// Turn one report into frame events. `base_seq` keeps event numbering monotonic across the
/// re-arms that a lease heartbeat causes.
pub fn to_event_views(
    rep: &LiveReport,
    surfaces: &[SurfaceView],
    slot_surface: Option<&str>,
    base_seq: u64,
) -> Vec<EventView> {
    rep.hits
        .iter()
        .map(|h| {
            let at = attach_by_address(surfaces, rep.addr, rep.len, slot_surface);
            EventView {
                seq: base_seq + h.seq as u64,
                elapsed_ms: h.elapsed_ms as u64,
                surface: at.surface.clone().unwrap_or_else(|| "(unattributed)".into()),
                field: at.field.clone(),
                how: at.how.to_string(),
                slot_surface: slot_surface.map(str::to_string),
                disagreement: at.disagreement.clone(),
                addr: rep.addr,
                tid: h.tid,
                // ⚠ BOTH, always, and labelled: rip is the NEXT instruction.
                rip: h.rip,
                rip_vaddr: h.rip_vaddr,
                writer: h.writer,
                writer_vaddr: h.writer_vaddr,
                writer_text: h.writer_text.clone().unwrap_or_else(|| "(undecodable)".into()),
                writer_confidence: h.writer_confidence.clone(),
                writer_quotable: h.writer_is_quotable(),
                value_after: h.value_after.clone(),
            }
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn extent_is_unclamped_where_the_display_parser_clamps() {
        // The display parser clamps ptr[38] to 16 entries; attribution must not.
        assert_eq!(declared_extent("ptr[38]"), Some(38 * 8));
        assert_eq!(declared_extent("u8[64]"), Some(64));
        assert_eq!(declared_extent("i32"), Some(4));
        assert_eq!(declared_extent("char[16]"), Some(16));
        // …and a type with no unambiguous extent is None, not a guess.
        assert_eq!(declared_extent("struct[]"), None);
        assert_eq!(declared_extent("u8[40*0xD8]"), None);
        assert_eq!(declared_extent("[U]"), None);
    }

    #[test]
    fn required_keys_are_actually_checked() {
        let good = serde_json::json!({
            "pid": 1, "addr": 16, "addr_vaddr": null, "len": 8, "rw": "write", "slot": 0,
            "threads_armed": 1, "threads_failed": [], "follow_clone": false, "clones_armed": 0,
            "unattributed_sigtraps": 0, "foreign_stops": 0, "seconds": 0.1,
            "stop_reason": "x", "hits": []
        });
        assert!(missing_required_keys(&good).is_empty());
        // The inversion: drop one key and the checker must name it.
        let mut bad = good.clone();
        bad.as_object_mut().unwrap().remove("stop_reason");
        assert_eq!(missing_required_keys(&bad), vec!["stop_reason".to_string()]);
    }
}

