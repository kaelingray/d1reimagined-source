/// ⭐ **A RECORDED REPORT, TURNED BACK INTO THE CHILD STATUS THAT PRODUCED IT** - so a replay shows
/// the same badge a live child would.
///
/// ⛔ WHY THIS IS NOT AN INVENTION. `d1-live --json` writes its report **once, on the way out**;
/// the document *is* the child's exit statement, and `ChildMgr::stop` classifies a live child from
/// exactly these fields - `hits.is_empty()` ⇒ `NoHit`, otherwise `Finished` - on **stdout
/// parseability, never on the exit code**. This does the same classification on the same fields.
///
/// ⚠ WHAT IT CANNOT KNOW, stated rather than assumed: nothing here observed a process. The receipt
/// is stamped `how: "replayed-report"` and carries **`confirmed_disarm: false`**, because a disarm
/// is a *positive* statement about a process that exited on its own path - and no process exited
/// here. ⇒ a replay can never launder itself into a disarm receipt, and
/// `child_mgr::unconfirmed_receipts` is not fed by this (it reads the recorder, which a replay
/// never writes to).
///
/// ⛔ Without it, `--events` produced **no badge at all**: attribution is by ADDRESS, a recorded
/// address does not land in a snapshot's surfaces, and with `ChildStatus::None` the badge path has
/// no armed spec to speak of. An event plane that silently shows nothing is the exact failure this
/// crate exists to prevent, one layer up.
pub fn replayed_child_status(rep: &LiveReport, surface: Option<String>) -> crate::frame::ChildStatus {
    use crate::frame::{ChildStatus, StopReceipt, WatchSpecView};
    let spec = WatchSpecView {
        surface,
        addr_expr: match rep.addr_vaddr {
            Some(v) => format!("v:{v:#x}"),
            None => format!("a:{:#x}", rep.addr),
        },
        resolved: rep.addr,
        len: rep.len,
        rw: rep.rw.clone(),
        slot: rep.slot,
        count: rep.hits.len(),
        lease_s: rep.seconds,
    };
    let receipt = StopReceipt {
        child_pid: 0,
        target_pid: rep.pid,
        how: "replayed-report".into(),
        exit_code: None,
        exit_signal: None,
        waited_ms: 0,
        // ⛔ FALSE, deliberately. Nothing was observed to exit, so nothing may be claimed to have
        //    disarmed. A replay that stamped `true` would be a fabricated safety receipt.
        confirmed_disarm: false,
        stop_reason: Some(rep.stop_reason.clone()),
        complaints: vec![
            "⚠ REPLAY - this status was reconstructed from a recorded document. No process was \
             observed, and no disarm is claimed."
                .into(),
        ],
        hits: rep.hits.len(),
    };
    if rep.hits.is_empty() {
        ChildStatus::NoHit {
            spec,
            watched_s: rep.seconds,
            stop_reason: rep.stop_reason.clone(),
            why: format!(
                "⚠ NO HIT in {:.1}s ({}). This is evidence ONLY about the {} thread(s) armed at \
                 start. It is NOT evidence that nothing writes {:#x}.",
                rep.seconds, rep.stop_reason, rep.threads_armed, rep.addr
            ),
            receipt,
        }
    } else {
        ChildStatus::Finished {
            spec,
            hits: rep.hits.len() as u32,
            stop_reason: rep.stop_reason.clone(),
            receipt,
        }
    }
}
