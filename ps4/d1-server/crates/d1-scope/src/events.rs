//! The event plane's **reader**: `d1-live --json watch`'s report, parsed, and each hit attached to
//! a registry surface **by address**.
//!
//! # ⭐ WHY THIS IS A MIRROR AND NOT AN IMPORT, STATED HONESTLY
//!
//! `d1_live::watch::WatchReport` is `Serialize` only - it has no `Deserialize`, and `d1-live` is
//! not this lane's to edit. So the shape is declared a second time here. That is **exactly** the
//! situation `design/format-description.md` warns about, so it is fenced two ways rather than
//! waved through:
//!
//! 1. ⛔ **The mirror is a CONSUMER-SIDE SCHEMA SHIELD, not a definition.** Nothing in d1-scope
//!    ever *emits* this document; d1-live is and remains the only writer. A shield that only reads
//!    cannot desynchronise a producer, which is the failure the no-format-twice rule exists to
//!    prevent.
//! 2. ⛔ **A permissive `#[serde(default)]` mirror DEGRADES SILENTLY**, which is worse than
//!    failing: rename `writer_text` upstream and every event quietly loses its writer while the
//!    parse still "succeeds". So the mirror is paired with [`missing_required_keys`], a check
//!    against the *raw* JSON that names every key we depend on. Control #6 runs it against a
//!    checked-in fixture **and** against a report generated by today's `d1-live` binary - the
//!    second leg is the drift detector, and it is the one that will fire.
//!
//! ⇒ If `d1-live` ever derives `Deserialize` on its own report, delete this mirror and import it.
//! That edit belongs to d1-live's owner. Until then, the shield plus the key check is the strongest
//! form available to a lane that may not touch the producer.
//!
//! # ⚠ The trap this module exists to keep visible
//!
//! **A data breakpoint is a trap: the reported `rip` is the instruction AFTER the store.** Both the
//! raw register and the decoded store are carried through to [`crate::frame::EventView`], never
//! collapsed into one "address", and [`EventView::writer`] is the one a reader may quote. Control
//! #7 asserts they are both present *and distinct* on a real recorded fixture - an instrument that
//! silently reported the same number twice would name the wrong basic block and look fine doing it.

