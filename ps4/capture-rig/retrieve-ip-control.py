#!/usr/bin/env python3
"""Behavioural control for the fork-local RetrieveIp() change in shadPS4-d1trace.

WHY THIS SHAPE: the axis under test is "does the SHIPPED code pick the right address in the
topology the capture rig actually uses". So the body of NetUtilInternal::RetrieveIp is EXTRACTED
VERBATIM from net_util.cpp, wrapped in a minimal shim, compiled and executed. Nothing is
transcribed; if the source drifts, this control compiles the drifted source. If extraction fails,
the control exits 2 rather than silently testing a stale copy.

Three arms, each with the answer that must come back:

  A  host namespace, default route present            -> the ROUTABLE address (203.0.113.84 here),
                                                         NOT merely the first non-loopback iface
  B  contained namespace, address but NO default route -> that namespace's own address (10.77.0.2)
  C  contained namespace, default route to an unreachable gateway
                                                       -> the namespace's own address, PROMPTLY
                                                          (upstream's SOCK_STREAM probe hangs here
                                                           for the kernel SYN-retry budget)

Arm A is the discriminating one: a naive "getifaddrs, first non-IFF_LOOPBACK" implementation
passes B and C and FAILS A on any multi-homed host. This box has five non-loopback interfaces.

Exit 0 = all arms pass. Exit 2 = a control failed or could not be run; do not cite the change.
"""

import os
import re
import shutil
import socket
import subprocess
import sys
import tempfile

# ⚠ The default was once the literal string "$HOME/...", which Python does not expand, so an
# unset SHADPS4_SRC silently produced a path that could never exist.
SRC = (
    os.environ.get("SHADPS4_SRC")
    or os.path.join(os.path.expanduser("~"), "dev", "shadPS4-d1trace")
) + "/src/core/libraries/network/net_util.cpp"

SHIM = r"""
// Auto-generated by capture-rig/retrieve-ip-control.py -- do not edit.
#include <cerrno>
#include <cstdio>
#include <cstring>
#include <mutex>
#include <string>
#include <arpa/inet.h>
#include <ifaddrs.h>
#include <net/if.h>
#include <netinet/in.h>
#include <sys/socket.h>
#include <unistd.h>

typedef unsigned int u32;

static std::string g_log;
#define LOG_INFO(cat, ...)  do { char _b[512]; snprintf(_b, sizeof(_b), __VA_ARGS__); g_log += _b; g_log += "\n"; } while (0)
#define LOG_ERROR(cat, ...) do { char _b[512]; snprintf(_b, sizeof(_b), __VA_ARGS__); g_log += _b; g_log += "\n"; } while (0)
#define Lib_Net 0

// fmt-style "{}" placeholders in the shipped log calls become printf "%s"/"%s" via these
// trivial overloads; the log text is not what is under test, the returned address is.
struct NetUtilInternal {
    std::mutex m_mutex;
    std::string ip;
    bool RetrieveIp();
};

__BODY__

int main() {
    NetUtilInternal n;
    bool ok = n.RetrieveIp();
    printf("%s|%s\n", ok ? "true" : "false", n.ip.c_str());
    return 0;
}
"""


def fail(msg):
    print("CONTROL FAILED: " + msg, file=sys.stderr)
    sys.exit(2)


def extract_body(text):
    start = text.find("bool NetUtilInternal::RetrieveIp() {")
    if start < 0:
        fail("could not find 'bool NetUtilInternal::RetrieveIp() {' in " + SRC)
    i = text.index("{", start)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[start:j + 1]
    fail("unbalanced braces while extracting RetrieveIp()")


def neutralise_fmt(body):
    """The shipped code logs with fmt-style '{}'; the shim's LOG_* macros are printf. Rewrite the
    placeholders inside LOG_ calls only, and give std::string arguments .c_str(). The log TEXT is
    not what is under test -- the returned address is -- so this rewrite cannot mask a defect in
    the address-selection logic, which is transcribed untouched."""
    def fix(m):
        return m.group(0).replace("{}", "%s")

    body = re.sub(r'LOG_(?:INFO|ERROR)\(Lib_Net,[\s\S]*?\);', fix, body)
    body = body.replace("ip, chosen_if);", "ip.c_str(), chosen_if.c_str());")
    body = body.replace('"local ip %s (route probe)", ip);',
                        '"local ip %s (route probe)", ip.c_str());')
    return body


def build():
    text = open(SRC).read()
    body = neutralise_fmt(extract_body(text))
    for needle in ("SOCK_DGRAM", "getifaddrs", "IFF_LOOPBACK"):
        if needle not in body:
            fail("extracted body does not contain %r -- extraction is wrong, or the change was "
                 "reverted" % needle)
    d = tempfile.mkdtemp(prefix="retrieveip-")
    cpp = os.path.join(d, "t.cpp")
    open(cpp, "w").write(SHIM.replace("__BODY__", body))
    exe = os.path.join(d, "t")
    r = subprocess.run(["g++", "-std=c++20", "-O0", "-o", exe, cpp],
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stderr[-3000:], file=sys.stderr)
        fail("could not compile the extracted body")
    return d, exe


def run_arm(name, exe, netns_script, expect_pred, expect_desc, max_seconds):
    if netns_script is None:
        cmd = [exe]
    else:
        cmd = ["unshare", "-rn", "bash", "-c", netns_script + " " + exe]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=max_seconds)
    except subprocess.TimeoutExpired:
        print("  FAIL  %-46s TIMED OUT after %ss" % (name, max_seconds))
        return False
    out = (r.stdout or "").strip().splitlines()
    if not out:
        print("  FAIL  %-46s no output (stderr: %s)" % (name, (r.stderr or "").strip()[:200]))
        return False
    ok_str, _, addr = out[-1].partition("|")
    good = (ok_str == "true") and expect_pred(addr)
    print("  %s  %-46s -> %-15s  (want %s)" % ("PASS" if good else "FAIL", name, addr or "<none>",
                                               expect_desc))
    return good


NETNS = ("ip link add d1net type dummy && ip addr add 10.77.0.2/24 dev d1net && "
         "ip link set d1net up && ip link set lo up &&")
NETNS_BLACKHOLE = NETNS + " ip route add default via 10.77.0.1 dev d1net &&"


def host_routable_address():
    """The address the host kernel would actually source from -- computed independently of the
    code under test, so arm A compares against the kernel, not against our own constant."""
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        s.connect(("1.1.1.1", 80))
        return s.getsockname()[0]
    except OSError:
        return None
    finally:
        s.close()


# The implementation the plan document originally prescribed: "replace the connect-probe with
# getifaddrs(), taking the first non-IFF_LOOPBACK AF_INET address". It is compiled and run through
# the same three arms by --meta, and it MUST FAIL arm A on a multi-homed host. That is the proof
# that arm A discriminates rather than decorates.
NAIVE_BODY = r"""
bool NetUtilInternal::RetrieveIp() {
    std::scoped_lock lock{m_mutex};
    ifaddrs* ifap = nullptr;
    if (getifaddrs(&ifap) != 0) {
        return false;
    }
    bool found = false;
    for (ifaddrs* p = ifap; p != nullptr; p = p->ifa_next) {
        if (p->ifa_addr == nullptr || p->ifa_addr->sa_family != AF_INET) continue;
        if ((p->ifa_flags & IFF_LOOPBACK) != 0) continue;
        char b[INET_ADDRSTRLEN]{};
        const auto* sin = reinterpret_cast<const sockaddr_in*>(p->ifa_addr);
        inet_ntop(AF_INET, &sin->sin_addr, b, INET_ADDRSTRLEN);
        ip = b;
        found = true;
        break;
    }
    freeifaddrs(ifap);
    return found;
}
"""


def build_from(body):
    d = tempfile.mkdtemp(prefix="retrieveip-")
    cpp = os.path.join(d, "t.cpp")
    open(cpp, "w").write(SHIM.replace("__BODY__", body))
    exe = os.path.join(d, "t")
    r = subprocess.run(["g++", "-std=c++20", "-O0", "-o", exe, cpp],
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stderr[-3000:], file=sys.stderr)
        fail("could not compile variant")
    return d, exe


def meta():
    """Prove the harness can fail: the naive getifaddrs-only implementation must NOT pass arm A."""
    routable = host_routable_address()
    if routable is None:
        fail("--meta needs a host default route to be meaningful")
    d, exe = build_from(NAIVE_BODY)
    print("META: running the naive getifaddrs-only variant through arm A; it MUST FAIL.")
    passed = run_arm("A host, default route present [NAIVE VARIANT]", exe, None,
                     lambda a: a == routable, "the routable source %s" % routable, 30)
    shutil.rmtree(d, ignore_errors=True)
    if passed:
        print("META FAILED: the naive variant passed arm A, so arm A does not discriminate.")
        return 2
    print("META PASS: arm A rejects the naive variant, so arm A is a real control.")
    return 0


def main():
    if shutil.which("g++") is None:
        fail("g++ not available")
    if "--meta" in sys.argv:
        return meta()
    d, exe = build()
    results = []

    routable = host_routable_address()
    if routable is None:
        print("  SKIP  arm A (host has no default route)")
    else:
        others = []
        try:
            out = subprocess.run(["ip", "-o", "-4", "addr", "show"],
                                 capture_output=True, text=True).stdout
            others = [l.split()[3].split("/")[0] for l in out.splitlines()
                      if l.split()[1] != "lo"]
        except Exception:
            pass
        if len(others) < 2:
            print("  NOTE  host is not multi-homed; arm A is present but not discriminating")
        results.append(run_arm(
            "A host, default route present", exe, None,
            lambda a: a == routable,
            "the kernel's own routable source %s, not merely a non-loopback iface" % routable, 30))

    results.append(run_arm(
        "B contained netns, no default route", exe, NETNS,
        lambda a: a == "10.77.0.2", "10.77.0.2", 30))

    results.append(run_arm(
        "C contained netns, unreachable gateway", exe, NETNS_BLACKHOLE,
        lambda a: a == "10.77.0.2", "10.77.0.2 promptly (upstream hangs here)", 20))

    shutil.rmtree(d, ignore_errors=True)
    if all(results) and results:
        print("ALL CONTROLS PASS  (%d arms)" % len(results))
        return 0
    print("CONTROLS FAILED")
    return 2


if __name__ == "__main__":
    sys.exit(main())
