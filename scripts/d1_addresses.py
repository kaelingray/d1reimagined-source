"""Index of the EBOOT addresses in the research notes (BLES01857 01.00, PPU virtual addresses).

Collects every hex value in the executable's range (0x10000-0x1ffffff) from notes/*.md and the
docstrings and comments of server/*.py and scripts/*.py, with the sentence around each mention, merges the curated names in notes/eboot-labels.tsv, and prints or
exports the result:

  python scripts/d1_addresses.py 0x3204a8 0x25715c     # name and every note mention
  python scripts/d1_addresses.py --grep slice          # search names, summaries and mentions
  python scripts/d1_addresses.py --markdown notes/eboot-addresses.md
  python scripts/d1_addresses.py --ghidra local\\d1_labels_ghidra.py

The Ghidra output is a Python script for Ghidra's script manager: it creates the curated labels
and puts the summary plus the first mentions in plate comments, on the decrypted EBOOT
(`rpcs3.exe --decrypt`, loaded as PowerPC:BE:64:A2ALT-32addr or the Cell variant). Values that
are sizes rather than addresses (multiples of 0x10000) are left out.
"""

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
LO, HI = 0x10000, 0x2000000
HEX = re.compile(r"(?<![0-9A-Za-z_+])0x0*([0-9a-fA-F]{5,7})\b")


def load_labels(path=REPO / "notes" / "eboot-labels.tsv"):
    labels = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        addr, name, summary = (line.split("\t") + ["", ""])[:3]
        labels[int(addr, 16)] = {"name": name, "summary": summary}
    return labels


def sentence(text, start, end):
    """The sentence (or table row / list item) around text[start:end], whitespace collapsed."""
    left = max(text.rfind(". ", 0, start), text.rfind("\n- ", 0, start), text.rfind("\n|", 0, start),
               text.rfind("\n\n", 0, start))
    rights = [i for i in (text.find(". ", end), text.find("\n- ", end), text.find("|\n", end),
                          text.find("\n\n", end)) if i >= 0]
    right = min(rights) + 1 if rights else len(text)
    s = re.sub(r"\s+", " ", text[left + 1:right]).strip(" -|.")
    if len(s) > 300:
        at = s.find(text[start:end])
        s = "..." + s[max(0, at - 140):at + 160] + "..."
    return s


SKIP = {"eboot-addresses.md", "d1_addresses.py", "d1_pkg.py", "test_d1_pkg.py"}


def collect():
    mentions = defaultdict(list)
    paths = sorted((REPO / "notes").glob("*.md")) + sorted((REPO / "server").glob("*.py")) + \
        sorted((REPO / "scripts").glob("*.py"))
    for path in paths:
        if path.name in SKIP:
            continue
        text = path.read_text(encoding="utf-8")
        for m in HEX.finditer(text):
            value = int(m.group(1), 16)
            if LO <= value < HI and value % 0x10000:
                line = text.count("\n", 0, m.start()) + 1
                ctx = sentence(text, m.start(), m.end())
                if not any(c["context"] == ctx for c in mentions[value]):
                    mentions[value].append({"file": path.relative_to(REPO).as_posix(), "line": line,
                                            "context": ctx})
    return mentions


def build():
    labels, mentions = load_labels(), collect()
    index = {}
    for addr in sorted(set(labels) | set(mentions)):
        index[addr] = {"address": f"0x{addr:x}", **labels.get(addr, {"name": "", "summary": ""}),
                       "mentions": mentions.get(addr, [])}
    return index


def link(m):
    """Link from notes/eboot-addresses.md to a mention."""
    f = m["file"]
    return (f[len("notes/"):] if f.startswith("notes/") else "../" + f) + f"#L{m['line']}"


def markdown(index):
    named = [e for e in index.values() if e["name"]]
    lines = ["# EBOOT address index (generated)", "",
             "Generated by `scripts/d1_addresses.py --markdown` from the notes, the server and script "
             "docstrings, and the curated "
             "names in [`eboot-labels.tsv`](eboot-labels.tsv); edit those, not this file. "
             f"{len(index)} addresses, {len(named)} named. BLES01857 01.00 PPU virtual addresses.", "",
             "## Named", "", "| Address | Name | Summary | Mentions |", "| --- | --- | --- | --- |"]
    for e in named:
        refs = ", ".join(f"[{Path(m['file']).stem}:{m['line']}]({link(m)})" for m in e["mentions"][:3])
        lines.append(f"| `{e['address']}` | `{e['name']}` | {e['summary'].replace('|', '/')} | {refs} |")
    lines += ["", "## Unnamed mentions", "", "First mention of each address not in the labels file.", ""]
    for e in index.values():
        if not e["name"] and e["mentions"]:
            m = e["mentions"][0]
            lines.append(f"- `{e['address']}` ({Path(m['file']).stem}:{m['line']}): "
                         f"{m['context'].replace('|', '/')}")
    return "\n".join(lines) + "\n"


def ghidra(index):
    rows = [(int(e["address"], 16), e["name"],
             "\n".join([e["summary"]] + [f"{m['file']}:{m['line']}: {m['context']}" for m in e["mentions"][:4]]))
            for e in index.values() if e["name"]]
    return f'''# Destiny 1 PS3 (BLES01857 01.00) labels from the d1xenia notes; generated by
# scripts/d1_addresses.py. Run from Ghidra's Script Manager on the decrypted EBOOT.
#@category D1
from ghidra.program.model.symbol import SourceType
from ghidra.program.model.listing import CodeUnit

ROWS = {json.dumps(rows, indent=0)}

space = currentProgram.getAddressFactory().getDefaultAddressSpace()
listing = currentProgram.getListing()
for addr, name, comment in ROWS:
    a = space.getAddress(addr)
    createLabel(a, "d1_" + name, True, SourceType.USER_DEFINED)
    cu = listing.getCodeUnitAt(a)
    if cu is not None:
        cu.setComment(CodeUnit.PLATE_COMMENT, comment)
print("labelled %d addresses" % len(ROWS))
'''


def show(index, addr):
    e = index.get(addr)
    if not e:
        print(f"0x{addr:x}: not in the notes or labels")
        return
    print(f"{e['address']} {e['name'] or '(unnamed)'}" + (f": {e['summary']}" if e["summary"] else ""))
    for m in e["mentions"]:
        print(f"  {m['file']}:{m['line']}: {m['context']}")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("addresses", nargs="*")
    ap.add_argument("--grep")
    ap.add_argument("--markdown")
    ap.add_argument("--json")
    ap.add_argument("--ghidra")
    a = ap.parse_args(argv)
    index = build()
    for addr, label in load_labels().items():
        if not index[addr]["mentions"]:
            print(f"warning: labelled 0x{addr:x} ({label['name']}) is not mentioned in the notes",
                  file=sys.stderr)
    for text in a.addresses:
        show(index, int(text, 16))
    if a.grep:
        needle = a.grep.lower()
        for addr, e in index.items():
            blob = " ".join([e["name"], e["summary"]] + [m["context"] for m in e["mentions"]]).lower()
            if needle in blob:
                print(f"{e['address']:>10} {e['name'] or '-':32} {e['summary'] or e['mentions'][0]['context'][:100]}")
    if a.markdown:
        Path(a.markdown).write_text(markdown(index), encoding="utf-8")
    if a.json:
        Path(a.json).write_text(json.dumps(list(index.values()), indent=1), encoding="utf-8")
    if a.ghidra:
        Path(a.ghidra).write_text(ghidra(index), encoding="utf-8")


if __name__ == "__main__":
    main()
