"""Generate notes/content-matrix.md: one row per playable/loaded scenario of the target build.

The scenario list comes from the private mission catalog that `dump_mission_catalog.py` exports
from the local disc and update packages (`RESEARCH/ps3_updates/mission-catalog-0124/catalog.json`,
never committed). Status, evidence and next action per scenario are tracked in the repository in
`notes/content-status.json`; scenarios without an entry are NOT INVESTIGATED. Re-run after a new
catalog export or a status change:

  python scripts/build_content_matrix.py --catalog <local>/RESEARCH/ps3_updates/mission-catalog-0124/catalog.json

Categories are assigned from the scenario name prefix (an inference from naming, noted in the
output); a scenario's actual activity type is confirmed only once its activity definition is
decoded.
"""
import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
STATUSES = ("UNKNOWN", "NOT INVESTIGATED", "INVESTIGATING", "BLOCKED", "PARTIAL", "WORKING",
            "VERIFIED", "REGRESSION")

# (category, predicate on the scenario name), first match wins
CATEGORIES = [
    ("Story missions (act_*)", lambda n: n.startswith("act_") and "cinematic" not in n),
    ("Story / quest missions (mission_*)", lambda n: n.startswith("mission_")),
    ("Quest missions (quest_*)", lambda n: n.startswith("quest_")),
    ("Strikes", lambda n: n.startswith("strike_")),
    ("Raids", lambda n: n.startswith("raid_") or n.endswith("_raid_1")),
    ("Prison of Elders / arenas", lambda n: n.startswith("arena_")),
    ("Patrol spaces", lambda n: "_portal_" in n or n.startswith("patrol_") or "patrols" in n),
    ("Crucible maps", lambda n: n.startswith("pvp_")),
    ("Social spaces (Tower, Reef, Iron Temple variants)",
     lambda n: n.startswith("city_") or n.startswith("social_") or n.startswith("mercury_")),
    ("Orbit", lambda n: n == "orbit"),
    ("Cinematic scenarios", lambda n: n.startswith("cine_") or n.startswith("act_cinematic")),
    ("Ambient shells", lambda n: n.startswith("ambient_")),
]


def category(name):
    for label, test in CATEGORIES:
        if test(name):
            return label
    return "Other"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--catalog", type=Path, required=True)
    ap.add_argument("--status", type=Path, default=REPO / "notes" / "content-status.json")
    ap.add_argument("--out", type=Path, default=REPO / "notes" / "content-matrix.md")
    args = ap.parse_args(argv)

    catalog = json.loads(args.catalog.read_text(encoding="utf-8"))
    status = json.loads(args.status.read_text(encoding="utf-8")) if args.status.exists() else {}
    for name, entry in status.items():
        if entry.get("status") not in STATUSES:
            sys.exit(f"{name}: unknown status {entry.get('status')!r}")

    scenarios = {}
    for item in catalog["scenarios"]:
        name = item["name"].split(":")[0]
        scenarios.setdefault(name, item)
    unknown = sorted(set(status) - set(scenarios))
    if unknown:
        sys.exit(f"status entries for scenarios missing from the catalog: {unknown}")

    groups = {}
    for name in sorted(scenarios):
        groups.setdefault(category(name), []).append(name)

    lines = [
        "# Content matrix (generated)",
        "",
        "Generated by `scripts/build_content_matrix.py` from the private 01.24 mission catalog "
        f"({len(scenarios)} distinct scenarios in the local disc/update packages) and the tracked "
        "statuses in `content-status.json`. Do not edit by hand: change the status file and re-run.",
        "Categories come from scenario-name prefixes (inferred until each activity definition is "
        "decoded). Scenarios absent here are not in the local packages - see the DLC presence "
        "question in `feature-matrix.md`.",
        "",
    ]
    totals = {}
    for label, _ in CATEGORIES + [("Other", None)]:
        names = groups.get(label)
        if not names:
            continue
        lines += [f"## {label} ({len(names)})", "",
                  "| Scenario | Bubbles | Status | Evidence | Next action |",
                  "| --- | --- | --- | --- | --- |"]
        for name in names:
            entry = status.get(name, {})
            state = entry.get("status", "NOT INVESTIGATED")
            totals[state] = totals.get(state, 0) + 1
            lines.append(f"| `{name}` | {scenarios[name].get('bubble_count', '')} | {state} | "
                         f"{entry.get('evidence', '')} | {entry.get('next', '')} |")
        lines.append("")
    summary = ", ".join(f"{k}: {v}" for k, v in sorted(totals.items()))
    lines.insert(5, f"Totals: {summary}.")
    lines.insert(6, "")
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.out} ({len(scenarios)} scenarios; {summary})")


if __name__ == "__main__":
    main()
